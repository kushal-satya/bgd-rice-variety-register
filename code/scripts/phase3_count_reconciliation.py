"""Count reconciliation: prints the numbers and writes 06_validation/count_reconciliation.md.

Run from the project root after scripts/assemble.py (it reads 05_output/rice_varieties.csv, the not-approved file and
05_output/final/bgd_nsb_decisions_full.csv). Since version 1.2 (REV2, 2026-11-10) the memo is generated, not hand-written,
so its counts always follow the register; the explanatory sentences that cannot be computed (sources of the external
counts) are fixed text and are checked against the computed numbers by the asserts-in-words below ('ok' / 'DIFFERS').
"""
import datetime
import pathlib
import sys

import pandas as pd

sys.path.insert(0, "scripts")
from lib_keys import make_key

ROOT = pathlib.Path(__file__).resolve().parents[1]
r = pd.read_csv(ROOT / "05_output/rice_varieties.csv", dtype=str).fillna("")
na = pd.read_csv(ROOT / "05_output/rice_not_approved_or_unresolved.csv", dtype=str).fillna("")
REMAP = pd.read_csv(ROOT / "04_working/key_remap.csv", dtype=str).set_index("old_key")["new_key"].to_dict()
r["key"] = r.variety_id.str.replace("RICE-", "", regex=False)
hyb = r["type"].str.lower().str.contains("hybrid") | r.key.str.contains("HYBRID") | r.key.str.startswith("HYB_")
out = {}
out["total"] = len(r)
out["by_category"] = r.release_category.value_counts().to_dict()
out["by_type"] = {"hybrid": int(hyb.sum()), "inbred": int((~hyb).sum())}
out["BRRI inbred (BR+BRRI dhan)"] = int(r.key.str.match(r"^(BR\d+|BRRI_DHAN\d+)$").sum())
out["BRRI hybrid"] = int(r.key.str.match(r"^BRRI_HYBRID\d+$").sum())
out["BINA (Binadhan+Iratom+Binashail)"] = int(r.key.str.match(r"^(BINADHAN\d+|IRATOM\d+|BINASHAIL|BINA_HYBRID\d+)$").sum())
out["private hybrids HYB_"] = int(r.key.str.startswith("HYB_").sum())
t27 = pd.read_csv(ROOT / "03_extracted/tables/spia2025_table27.csv", dtype=str).fillna("")
namecol = [c for c in t27.columns if "variety" in c.lower()][0]
t27["key"] = t27[namecol].map(make_key).map(lambda k: REMAP.get(k, k) if isinstance(k, str) else k)
ours = r[(r.approval_date.str[:4] <= "2023") & ~r.key.str.startswith("HYB_") & ~r.key.str.startswith("PVT_")]
only_ours = sorted(set(ours.key) - set(t27.key.dropna()))
only_t27 = sorted(set(t27.key.dropna()) - set(r.key))
out["SPIA T27 rows"] = len(t27)
out["our public+NGO rows approved <=2023"] = len(ours)
out["ours only"] = only_ours
out["SPIA only"] = only_t27
dec = pd.read_csv(ROOT / "05_output/final/bgd_nsb_decisions_full.csv", dtype=str).fillna("")
out["NSB decision rows"] = len(dec)
out["NSB decision types"] = dec.decision_type.value_counts().to_dict()
for k, v in out.items():
    print(f"{k}: {v}")

name = dict(zip(r.key, r.variety_name))
cat = out["by_category"]
ok = lambda a, b: "ok" if a == b else "DIFFERS"
n_hyb_priv = int(r.key.str.startswith("HYB_").sum())
n_hyb_brri = out["BRRI hybrid"]
n_hyb_other = out["by_type"]["hybrid"] - n_hyb_priv - n_hyb_brri
spia_total = len(ours) - len(only_ours) + len(only_t27)
dt = out["NSB decision types"]
L = [f"# Count reconciliation (version 1.2, generated {datetime.date.today().isoformat()})", "",
     "Generated by `scripts/phase3_count_reconciliation.py` from `05_output/rice_varieties.csv`, "
     "`05_output/rice_not_approved_or_unresolved.csv` and `05_output/final/bgd_nsb_decisions_full.csv` "
     "(run inside `scripts/rebuild_all.sh`).", "",
     "## Our table", f"**{len(r)} approved rice varieties.**",
     f"- By route: {cat.get('NSB_release', 0)} NSB releases, {cat.get('NSB_registration', 0)} NSB registrations, "
     f"{cat.get('pre_NSB_recommended', 0)} recommended before the NSB existed.",
     f"- By type: {out['by_type']['hybrid']} hybrids ({n_hyb_priv} private or BADC, {n_hyb_brri} BRRI, {n_hyb_other} other public) "
     f"and {out['by_type']['inbred']} inbreds.",
     "- Version 1.1 merged Bri-shail into BR4 (444 to 443); version 1.2 admits Iratom-38 (approved as 'Iratom' at NSB 4 in 1975, "
     "cultivation suspended at NSB 14 in 1981), so the register again has 444 rows, and merges the unresolved name "
     "'BU Aromatic dhan2' into BU dhan2.", "",
     f"{len(na)} further names sit in `bgd_rice_not_approved_or_unresolved.csv`:"]
for x in na.itertuples():
    why = getattr(x, "status", "") or getattr(x, "decision_conditions", "") or "no approval on record; see bgd_variety_status.csv and bgd_variety_events.csv"
    L.append(f"- {x.variety_name or x.variety_id} ({x.official_name_bn}): {why[:160]}")
L += ["", "## Check 1: public and NGO varieties against SPIA 2025 Table 27 (independent CGIAR list, 1970-2023)",
      "| | count |", "|---|---|",
      f"| Our public, NGO and pre-NSB rows approved by 2023 | {len(ours)} |",
      f"| minus our rows SPIA does not list | -{len(only_ours)} |",
      f"| plus SPIA rows we did not admit | +{len(only_t27)} |",
      f"| **= SPIA Table 27** | **{spia_total}** ({ok(spia_total, len(t27))}; table has {len(t27)} rows) |", "",
      "Rows that are ours only: " + ", ".join(name.get(k, k) for k in only_ours) + ".",
      "Pre-1970 introductions (IR8, IR5, IR20, Pajam, Purbachi) lie outside SPIA's window; Iratom-38, whose cultivation the Board "
      "suspended in 1981, is not in SPIA's list; the others are university and NGO varieties and a public hybrid that SPIA does not list.",
      "SPIA rows not in the register: " + (", ".join(only_t27) if only_t27 else "none") + ".", "",
      "## Check 2: institute counts", "| list | stated | ours | note |", "|---|---|---|---|",
      f"| BRRI website (23 Apr 2026) | 127 = 117 inbred + 10 hybrid | {out['BRRI inbred (BR+BRRI dhan)']} BR/BRRI dhan + "
      f"{n_hyb_brri} BRRI hybrid = {out['BRRI inbred (BR+BRRI dhan)'] + n_hyb_brri} ({ok(out['BRRI inbred (BR+BRRI dhan)'] + n_hyb_brri, 127)}) "
      "| BR13 does not exist in any source |",
      f"| BINA (at-a-glance table + NSB 115) | 28 | {out['BINA (Binadhan+Iratom+Binashail)']} ({ok(out['BINA (Binadhan+Iratom+Binashail)'], 28)}) "
      "| includes Iratom-38 since v1.2. BINA's own table lists 27 rows (Binadhan-7 twice) and omits Binadhan-27, approved at NSB 115 |",
      "| BRRI Adhunik Dhaner Chash 2025 Table 1 | 115 (to BRRI dhan108, hybrid 8) | all present | the 12 releases of 2025-26 come "
      "from fact sheets and NSB minutes |", "",
      "## Check 3: hybrids against the MoA cumulative list (1998 to 05 Feb 2026)", "| | count |", "|---|---|",
      "| MoA 2026 rows | 271 (serial 125 printed blank) |", "| distinct varieties in it | 270 (rows 108 and 112 are the same Bayer hybrid) |",
      "| plus hybrids missing from MoA 2026 | +9: seven registered at the 115th meeting itself, which the list does not yet include, "
      "and two the list omits (ACI Formulation-5, 112th meeting; Supreme Subarna-3, 75th meeting, documented only in the minutes "
      "and the 2016 compendium) |",
      f"| **= our hybrid rows** | **{out['by_type']['hybrid']}** ({ok(out['by_type']['hybrid'], 279)}) |", "",
      "See `hybrid_count_reconciliation.md` for the secondary figure of 255 registrations.", "",
      "## Check 4: NSB decision register (minutes 1-115)",
      f"- **{len(dec)} decision rows** (one row per variety and decision; the generic 'Iratom' approval of NSB 4 is one row each "
      "for Iratom-24 and Iratom-38): " + ", ".join(f"{v} {k}" for k, v in dt.items()) + ".",
      "- **No rice variety was ever formally denotified.** The Board suspended seed multiplication of IR8 and IR20 (NSB 7, 1976) "
      "and the cultivation of Iratom-38 (NSB 14, 1981), and in 2021 (NSB 105) deferred a proposal to denotify 20 varieties.",
      "- Extensions, renames, deferrals and refusals are not separate varieties; pre-NSB varieties have no NSB decision; a few "
      "releases are documented only in SCA lists or gazettes."]
(ROOT / "06_validation/count_reconciliation.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote 06_validation/count_reconciliation.md")
